export function getVisibleHelpGuides(roleCodes: RoleCode[], search = "") {
  const normalizedSearch = search.trim().toLocaleLowerCase();
  return helpGuides.filter((guide) => {
    const hasRole = roleCodes.some((role) => guide.roles.includes(role));
    if (!hasRole) return false;
    if (!normalizedSearch) return true;
    const searchableText = [
      guide.title,
      guide.summary,
      guide.routeLabel,
      ...guide.keywords,
      ...guide.steps,
      guide.note ?? "",
    ]
      .join(" ")
      .toLocaleLowerCase();
    return searchableText.includes(normalizedSearch);
  });
}
